# Task 4: Continuing Professional Development (CPD)
#
# This year I want to improve my programming, problem-solving, communication,
# and teamwork skills. I can write simple programs, but I want to become more
# confident designing larger solutions, debugging independently, and explaining
# my decisions. I also want to develop my understanding of databases, Git, and
# cybersecurity because these skills are useful across many computing careers.
#
# I will use the CPD cycle by identifying my learning needs, profiling my
# current competence, planning development, completing development activities,
# keeping a personal development record, and assessing, evaluating, and
# reflecting on the results. First, I will assess my current ability by
# reviewing my coursework and identifying topics that cause difficulty. I will
# then set measurable goals: complete two
# Python practice exercises each week, build one small project each term, use
# Git for every project, and study one database or cybersecurity topic each
# month. I will plan regular study sessions and use lectures, documentation,
# tutorials, coding exercises, and feedback from tutors and classmates.
#
# During the action stage, I will practise by building practical projects rather
# than only reading theory. For example, I can create a small application that
# stores data in a database and document the development process in Git. I will
# keep a learning log containing completed tasks, mistakes, useful resources,
# and questions that still need investigation. This record will provide
# evidence of progress and help me notice recurring weaknesses.
#
# At the end of each month, I will reflect on what I learned, compare my results
# with my goals, and ask for feedback. If a goal is too easy, I will increase
# its difficulty; if it is unrealistic, I will divide it into smaller steps.
# By repeating this cycle, I can turn feedback into action and steadily improve
# both my technical ability and my confidence. My aim is to finish the year
# with a portfolio of well-documented projects and a clearer understanding of
# the computing role I would like to pursue.
