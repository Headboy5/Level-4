# Part I - Lecture Review Quiz

# 1. What is a computer?
# A computer is an electronic device that accepts data as input, processes it
# according to a set of instructions, stores data when needed, and produces
# useful information as output. It can perform calculations, make logical
# decisions, and communicate results quickly and accurately.

# 2. What is a computing system?
# A computing system is a dynamic entity used to solve problems and interact
# with its environment. It is composed of hardware, software, and the data
# that they manage.

# 3. How many layers are there in a typical computing system, what are they,
# and what is their purpose?
# A typical computing system is described using six layers:
#
# Information: The representation of data, including text, images, and audio,
# in binary form using 1s and 0s.
#
# Hardware: The physical components, from electronic gates and circuits to the
# CPU and memory, that carry out computing operations.
#
# Programming: Software instructions and programming languages used to solve
# problems and control the hardware.
#
# Operating systems: Software such as Windows, macOS, and Linux that manages
# resources and coordinates the hardware, programs, and data.
#
# Applications: Software that uses computing power to solve specific real-world
# problems, such as e-commerce, architectural design, or climate modelling.
#
# Communications: Networks, the Internet, and the World Wide Web that allow
# systems to exchange information and communicate globally.
#
# These layers work together so that users can interact with applications
# without needing to control the underlying hardware directly.

# 4. How do you understand computing as a discipline?
# I understand computing as the systematic study and application of computers,
# algorithms, data, software, hardware, and computational problem-solving.
# It includes much more than programming: it also covers systems, software,
# networking, data, artificial intelligence, and cybersecurity. Computing is
# both a scientific discipline for understanding computation and a practical
# discipline for designing useful, reliable, secure, and ethical solutions.


