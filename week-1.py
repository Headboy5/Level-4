# Task 2: Career Pathways Exploration
#
# Software developer / software engineer:
# Daily work includes analysing requirements, designing solutions, writing and
# reviewing code, testing features, fixing bugs, and collaborating with a team.
# Core skills include programming, algorithms, version control, debugging,
# problem-solving, communication, teamwork, and software design.
#
# Web developer:
# Daily work includes building and maintaining websites or web applications,
# creating responsive interfaces, connecting front ends to back ends, testing
# across browsers, and improving accessibility and performance. Core skills
# include HTML, CSS, JavaScript, web frameworks, APIs, Git, user experience,
# testing, and attention to detail.
#
# Data analyst:
# Daily work includes collecting and cleaning data, identifying trends,
# creating reports and dashboards, and explaining findings to stakeholders.
# Core skills include SQL, spreadsheets, statistics, data visualisation,
# Python or another analysis tool, critical thinking, and communication.
#
# Cybersecurity analyst:
# Daily work includes monitoring systems, investigating suspicious activity,
# assessing vulnerabilities, responding to incidents, and recommending security
# improvements. Core skills include networking, operating systems, security
# principles, risk analysis, incident response, attention to detail, and ethics.
#
# Network engineer:
# Daily work includes designing, configuring, monitoring, and troubleshooting
# wired and wireless networks. Core skills include networking protocols,
# routing and switching, cloud networking, security, diagnostics, documentation,
# and clear communication.
#
# Database administrator / database engineer:
# Daily work includes designing databases, managing access, backing up data,
# monitoring performance, and maintaining data availability and integrity.
# Core skills include SQL, database design, security, backup and recovery,
# performance tuning, scripting, and careful problem-solving.
#
# Cloud engineer:
# Daily work includes deploying and managing services in cloud platforms,
# automating infrastructure, monitoring reliability, and controlling costs.
# Core skills include cloud architecture, Linux, networking, security,
# scripting, infrastructure as code, automation, and troubleshooting.
#
# AI engineer:
# Daily work includes preparing data, developing and evaluating machine-learning
# models, integrating AI into applications, and monitoring their performance.
# Core skills include Python, mathematics, statistics, data preparation,
# machine learning, software engineering, critical thinking, and responsible AI.
#
# IT product manager:
# Daily work includes understanding user needs, setting product goals,
# prioritising features, coordinating technical teams, and evaluating product
# performance. Core skills include communication, planning, market awareness,
# leadership, prioritisation, problem-solving, and enough technical knowledge
# to make informed decisions.
#
# UX/UI designer:
# Daily work includes researching user needs, planning user journeys, creating
# wireframes and prototypes, testing designs, and working with developers.
# Core skills include user research, visual design, prototyping, accessibility,
# empathy, communication, and analytical thinking.


# Task 3: Professional Skills Exploration
#
# Technical skills:
# Programming: Writing instructions in languages such as Python, Java, or C++
# to create software and automate tasks.
#
# Algorithms and data structures: Designing efficient ways to process, search,
# organise, and store information.
#
# Databases and SQL: Storing, querying, updating, and protecting structured
# information.
#
# Networking: Understanding how devices communicate using networks, protocols,
# and services such as the internet.
#
# Cybersecurity: Protecting systems and data through secure design, access
# control, monitoring, risk management, and incident response.
#
# Version control: Tracking code changes and collaborating safely with tools
# such as Git.
#
# Testing and debugging: Finding defects, checking expected behaviour, and
# improving the reliability of software.
#
# Data analysis and visualisation: Cleaning data, identifying patterns, and
# presenting evidence clearly using charts, reports, or dashboards.
#
# Cloud and automation: Deploying services, managing computing resources, and
# reducing repetitive work through scripts and automated processes.
#
# Transferable skills:
# Communication: Explaining technical ideas clearly to both technical and
# non-technical audiences.
#
# Teamwork: Sharing responsibility, contributing reliably, listening to others,
# and resolving disagreements constructively.
#
# Problem-solving: Breaking complex problems into smaller steps and evaluating
# possible solutions logically.
#
# Critical thinking: Checking assumptions, judging evidence, and making
# reasoned decisions rather than accepting information without question.
#
# Adaptability and lifelong learning: Learning new tools and methods as
# technology, workplaces, and user needs change.
#
# Time management: Prioritising tasks, estimating effort, meeting deadlines,
# and managing competing responsibilities.
#
# Professionalism and ethics: Acting responsibly, respecting privacy and
# intellectual property, and considering the social effects of technology.
#
